#!/usr/bin/env node
/**
 * Proplync.mx · copy PropLync's shared rules into the Mini project
 * -----------------------------------------------------------------------------
 * WHY THIS EXISTS
 * PropLync Mini is its own Vercel project (Root Directory mini). Vercel bundles a
 * function with the files it imports, but it installs and traces npm packages only
 * inside mini/, so code imported from ../api could not find @supabase/supabase-js
 * at runtime (first deploy, 2026-11-20: ERR_MODULE_NOT_FOUND). So the Mini project
 * carries a copy of exactly the PropLync files it uses, under mini/api/_proplync/
 * (an underscore folder: never a function, never served), and declares the npm
 * packages they need in mini/package.json.
 *
 * WHY A COPY IS SAFE HERE
 * api/ stays the only place anyone edits. This script regenerates the copy from the
 * real import graph, and test/mini-shared.test.mjs fails whenever the copy differs
 * from api/, so a change to PropLync's rules can't silently skip the Mini.
 *
 *   node scripts/sync-mini-shared.mjs          rewrite the copy
 *   node scripts/sync-mini-shared.mjs --check  exit 1 if it is out of date
 * -----------------------------------------------------------------------------
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const API = join(ROOT, 'api');
const OUT = join(ROOT, 'mini', 'api', '_proplync');
// What mini/api/*.js imports from PropLync. The rest follows from their imports.
export const ENTRIES = ['onboard.js', 'extract.js', 'my-listings.js',
  '_lib/auth.js', '_lib/supabase.js', '_lib/ratelimit.js', '_lib/health.js', '_lib/plans.js', '_lib/notify.js', '_lib/events.js'];

const IMPORT = /(?:import|export)\s[^'"]*?from\s+['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)/g;

/** Every api/ file reachable from the entries, and the npm packages they import. */
export function graph() {
  const files = new Set(), packages = new Set(), queue = ENTRIES.map((e) => join(API, e));
  while (queue.length) {
    const f = queue.pop();
    if (files.has(f)) continue;
    files.add(f);
    for (const m of readFileSync(f, 'utf8').matchAll(IMPORT)) {
      const spec = m[1] || m[2];
      if (spec.startsWith('.')) queue.push(resolve(dirname(f), spec));
      else if (!spec.startsWith('node:')) packages.add(spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0]);
    }
  }
  return { files: [...files].sort(), packages: [...packages].sort() };
}

const HEADER = '// GENERATED by scripts/sync-mini-shared.mjs from api/. Do not edit: change api/ and re-run the script.\n';

function listOut(dir = OUT, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const n of readdirSync(dir)) { const p = join(dir, n); statSync(p).isDirectory() ? listOut(p, acc) : acc.push(p); }
  return acc;
}

/** Files whose copy is missing, stale or extra. Empty means in sync. */
export function drift() {
  const { files } = graph();
  const want = new Map(files.map((f) => [join(OUT, relative(API, f)), HEADER + readFileSync(f, 'utf8')]));
  const bad = [];
  for (const [p, body] of want) if (!existsSync(p) || readFileSync(p, 'utf8') !== body) bad.push(relative(ROOT, p));
  for (const p of listOut()) if (!want.has(p)) bad.push(relative(ROOT, p) + ' (extra)');
  return bad;
}

function write() {
  const { files, packages } = graph();
  rmSync(OUT, { recursive: true, force: true });
  for (const f of files) {
    const to = join(OUT, relative(API, f));
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, HEADER + readFileSync(f, 'utf8'));
  }
  const mini = JSON.parse(readFileSync(join(ROOT, 'mini', 'package.json'), 'utf8'));
  const root = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const missing = packages.filter((p) => !(mini.dependencies || {})[p]);
  console.log(`Copied ${files.length} files to ${relative(ROOT, OUT)}. Packages used: ${packages.join(', ')}`);
  if (missing.length) {
    mini.dependencies = { ...(mini.dependencies || {}) };
    for (const p of missing) mini.dependencies[p] = root.dependencies[p];
    writeFileSync(join(ROOT, 'mini', 'package.json'), JSON.stringify(mini, null, 2) + '\n');
    console.log(`Added to mini/package.json: ${missing.join(', ')} (run npm install in mini/ to refresh its lockfile)`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    const bad = drift();
    if (bad.length) { console.error('mini/api/_proplync is out of date:\n  ' + bad.join('\n  ') + '\nRun: node scripts/sync-mini-shared.mjs'); process.exit(1); }
    console.log('mini/api/_proplync is in sync with api/.');
  } else write();
}
